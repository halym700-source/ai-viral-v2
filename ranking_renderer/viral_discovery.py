#!/usr/bin/env python3
"""Discover popular REAL short-form video topics from YouTube's official API.

Research only: returned videos are NOT licensed for downloading/reposting.
Never extracts or downloads YouTube footage.
"""
import csv
import datetime as dt
import json
import math
import os
import urllib.parse
import urllib.request
from pathlib import Path

QUERIES = (
    "funniest real moments shorts",
    "real sports fails shorts",
    "crazy real motorcycle moments shorts",
    "amazing skateboard tricks shorts",
    "funny animal moments real shorts",
    "extreme sports moments shorts",
    "unexpected real life moments shorts",
)
SYNTHETIC_MARKERS = (
    "ai generated", "ai-generated", "made with ai", "ai video",
    "generated by ai", "sora ai", "veo 3", "text to video",
    "synthetic footage", "deepfake", "ai animation",
)

def request_json(endpoint, params, api_key):
    params = dict(params, key=api_key)
    url = "https://www.googleapis.com/youtube/v3/" + endpoint + "?" + urllib.parse.urlencode(params)
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent":"ReshRanksResearch/1.0"}), timeout=40) as response:
        return json.load(response)

def synthetic(text):
    return any(marker in text.lower() for marker in SYNTHETIC_MARKERS)

def rank_candidates(search_pages, detail_pages, now=None):
    """Rank genuine-looking candidates by views/day. Authenticity and rights remain UNVERIFIED."""
    now = now or dt.datetime.now(dt.timezone.utc)
    searches = {}
    for query, items in search_pages:
        for item in items:
            video_id = (item.get("id") or {}).get("videoId")
            if not video_id:
                continue
            snippet = item.get("snippet") or {}
            if synthetic(" ".join(str(snippet.get(k) or "") for k in ("title","description"))):
                continue
            if video_id not in searches:
                searches[video_id] = {"id":video_id, "title":snippet.get("title",""),
                    "channel":snippet.get("channelTitle",""), "published_at":snippet.get("publishedAt",""),
                    "query":query, "url":"https://www.youtube.com/watch?v="+video_id}
    results=[]
    for item in detail_pages:
        vid=item.get("id")
        if vid not in searches:
            continue
        snippet=item.get("snippet") or {}
        if synthetic(" ".join(str(snippet.get(k) or "") for k in ("title","description"))):
            continue
        stat=item.get("statistics") or {}
        views=int(stat.get("viewCount") or 0)
        try:
            published=dt.datetime.fromisoformat(searches[vid]["published_at"].replace("Z","+00:00"))
            age=max(1.0,(now-published).total_seconds()/86400)
        except (ValueError,TypeError):
            continue
        if views < 1000:
            continue
        rate=round(views/age,1)
        results.append(dict(searches[vid], views=views, age_days=round(age,1),
            views_per_day=rate, score=round(math.log1p(views)*math.log1p(rate),2),
            authenticity="unverified", reuse_rights="not_granted",
            approval="research_only", download_url=None))
    return sorted(results,key=lambda x:(x["score"],x["views"]),reverse=True)

def discover(api_key, now=None):
    if not api_key:
        raise ValueError("YOUTUBE_RESEARCH_API_KEY not set")
    now=now or dt.datetime.now(dt.timezone.utc)
    after=(now-dt.timedelta(days=30)).strftime("%Y-%m-%dT%H:%M:%SZ")
    search_pages=[]
    for query in QUERIES:
        data=request_json("search",{
            "part":"snippet","q":query,"type":"video","videoDuration":"short",
            "order":"viewCount","publishedAfter":after,"maxResults":25,
            "safeSearch":"moderate",
        },api_key)
        search_pages.append((query,data.get("items",[])))
    ids=list(dict.fromkeys(item["id"]["videoId"] for _,items in search_pages
        for item in items if item.get("id",{}).get("videoId")))
    details=[]
    for start in range(0,len(ids),50):
        data=request_json("videos",{
            "part":"snippet,statistics,contentDetails","id":",".join(ids[start:start+50])
        },api_key)
        details.extend(data.get("items",[]))
    return rank_candidates(search_pages,details,now)

def main():
    now=dt.datetime.now(dt.timezone.utc)
    items=discover(os.getenv("YOUTUBE_RESEARCH_API_KEY",""),now)
    output=Path("out")
    output.mkdir(parents=True,exist_ok=True)
    (output/"viral_research.json").write_text(json.dumps({
        "generated_at":now.isoformat(),"platform":"YouTube",
        "disclaimer":"Research only. Rights and authenticity are unverified. Never auto-download or reuse.",
        "videos":items[:50]},ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    columns=["id","title","channel","published_at","views","views_per_day","score",
             "query","url","authenticity","reuse_rights","approval"]
    with (output/"viral_research.csv").open("w",newline="",encoding="utf-8-sig") as f:
        writer=csv.DictWriter(f,fieldnames=columns,extrasaction="ignore")
        writer.writeheader()
        writer.writerows(items[:50])
    print(json.dumps({"found":len(items),"report":"out/viral_research.csv",
        "notice":"Research only; no download or publication rights inferred"}))

if __name__=="__main__":
    main()
